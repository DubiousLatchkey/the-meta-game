local function sprite(mask, color)
    local result = {}
    for row, bits in ipairs(mask) do
        result[row] = {}
        for column = 1, 5 do
            result[row][column] =
                (bits & (1 << (5 - column))) ~= 0
                and { color[1], color[2], color[3] } or _
        end
    end
    return result
end

