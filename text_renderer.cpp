int MeasureWidth(std::size_t characterCount) {
    if (characterCount == 0) {
        return 0;
    }
    return static_cast<int>(characterCount) * kGlyphAdvance - kGlyphScale;
}

void RenderText(
    Surface surface,
    const std::uint8_t* text,
    std::size_t characterCount,
    int x,
    int y,
    std::uint32_t color) {
    if (!surface.pixels || !text) {
        return;
    }

    for (std::size_t index = 0; index < characterCount; ++index) {
        DrawGlyph(
            surface,
            text[index],
            x + static_cast<int>(index) * kGlyphAdvance,
            y,
            color);
    }
}

