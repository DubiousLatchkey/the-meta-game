constexpr std::uint8_t kBlankGlyph[7] = {};
constexpr std::uint8_t kDeleteGlyph[7] = {
    0x1F, 0x11, 0x15, 0x15, 0x15, 0x11, 0x1F,
};

const std::uint8_t* GlyphFor(
    std::uint8_t value,
    std::uint8_t (&controlGlyph)[7]) {
    if (value <= 31) {
        controlGlyph[0] = 0x1F;
        controlGlyph[6] = 0x1F;
        for (int row = 0; row < 5; ++row) {
            const int bit = 4 - row;
            controlGlyph[row + 1] =
                static_cast<std::uint8_t>(
                    0x11 | ((value & (1u << bit)) != 0 ? 0x04 : 0x00));
        }
        return controlGlyph;
    }
    if (value == ' ') {
        return kBlankGlyph;
    }
    if (value >= '!' && value <= '@') {
        return kPunctuationAndDigits[value - '!'];
    }
    if (value >= 'A' && value <= 'Z') {
        return kUppercase[value - 'A'];
    }
    if (value >= '[' && value <= '`') {
        return kMiddlePunctuation[value - '['];
    }
    if (value >= 'a' && value <= 'z') {
        return kLowercase[value - 'a'];
    }
    if (value >= '{' && value <= '~') {
        return kFinalPunctuation[value - '{'];
    }
    return kDeleteGlyph;
}

void DrawRectangle(
    Surface surface,
    int x,
    int y,
    int width,
    int height,
    std::uint32_t color) {
    const int left = std::max(0, x);
    const int top = std::max(0, y);
    const int right = std::min(surface.width, x + width);
    const int bottom = std::min(surface.height, y + height);

    for (int pixelY = top; pixelY < bottom; ++pixelY) {
        std::uint32_t* row = surface.pixels + pixelY * surface.width;
        for (int pixelX = left; pixelX < right; ++pixelX) {
            row[pixelX] = color;
        }
    }
}

void DrawGlyph(
    Surface surface,
    std::uint8_t value,
    int x,
    int y,
    std::uint32_t color) {
    std::uint8_t controlGlyph[7] = {};
    const std::uint8_t* rows = GlyphFor(value, controlGlyph);
    for (int row = 0; row < 7; ++row) {
        for (int column = 0; column < 5; ++column) {
            if ((rows[row] & (1u << (4 - column))) != 0) {
                DrawRectangle(
                    surface,
                    x + column * kGlyphScale,
                    y + row * kGlyphScale,
                    kGlyphScale,
                    kGlyphScale,
                    color);
            }
        }
    }
}

